"""Generate technical metadata from the existing static pages, without a runtime."""
from pathlib import Path
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = 'https://' + (ROOT / 'CNAME').read_text().strip()
PAGES = ['index.html', 'buyers.html', 'partners.html', 'privacy.html', 'thank-you.html']
START, END = '<!-- Technical SEO: generated by scripts/seo.py -->', '<!-- /Technical SEO -->'

def generate():
    urls = []
    for name in PAGES:
        path = ROOT / name
        text = path.read_text()
        text = re.sub(re.escape(START) + r'.*?' + re.escape(END) + r'\n?', '', text, flags=re.S)
        text = re.sub(r'<script type="application/ld\+json">.*?</script>\s*', '', text, flags=re.S)
        url = ORIGIN + ('/' if name == 'index.html' else '/' + name)
        title = html.unescape(re.search(r'<title>(.*?)</title>', text).group(1))
        description = re.search(r'<meta name="description" content="([^"]*)">', text)
        if not description:
            description = re.search(r'<meta property="og:description" content="([^"]*)">', text)
            text = text.replace('</title>', '</title>\n<meta name="description" content="' + description.group(1) + '">', 1)
        description = html.unescape(description.group(1))
        text = re.sub(r'<meta property="og:url" content="[^"]*">', '<meta property="og:url" content="' + url + '">', text)
        graph = [
            {'@type': 'Organization', '@id': ORIGIN + '/#org', 'name': 'NuraniHomes', 'alternateName': 'نورانی', 'url': ORIGIN + '/', 'logo': ORIGIN + '/icon-512.png', 'email': 'anurani@nuranihomes.com'},
            {'@type': 'WebSite', '@id': ORIGIN + '/#website', 'name': 'NuraniHomes', 'url': ORIGIN + '/', 'publisher': {'@id': ORIGIN + '/#org'}},
            {'@type': 'WebPage', '@id': url + '#webpage', 'url': url, 'name': title, 'isPartOf': {'@id': ORIGIN + '/#website'}, 'inLanguage': 'en'}
        ]
        lines = [START, '<link rel="canonical" href="' + url + '">', '<meta name="referrer" content="strict-origin-when-cross-origin">']
        if name == 'thank-you.html':
            lines.append('<meta name="robots" content="noindex, follow">')
        else:
            urls.append(url)
        for key, value in [('twitter:title', title), ('twitter:description', description), ('twitter:image', ORIGIN + '/og-image.jpg')]:
            lines.append('<meta name="' + key + '" content="' + html.escape(value, quote=True) + '">')
        lines.extend(['<script type="application/ld+json">', json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False).replace('<', '\\u003c'), '</script>', END])
        path.write_text(text.replace('</head>', '\n'.join(lines) + '\n</head>'))
    (ROOT / 'sitemap.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join('  <url><loc>' + url + '</loc></url>\n' for url in urls) + '</urlset>\n')
    (ROOT / 'robots.txt').write_text('User-agent: *\nAllow: /\n\nSitemap: ' + ORIGIN + '/sitemap.xml\n')

if __name__ == '__main__':
    generate()
